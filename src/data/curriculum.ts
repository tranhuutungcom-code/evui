import type { Lesson, Level, LevelId, Unit } from '../types/curriculum'

function buildPlannedUnits(
  levelId: LevelId,
  firstUnit: Unit,
  plannedTitles: Array<{ title: string; subtitle: string; emoji: string }>
): Unit[] {
  const restUnits: Unit[] = plannedTitles.map((item, idx) => ({
    id: `${levelId}-U${idx + 2}`,
    levelId,
    order: idx + 2,
    title: item.title,
    subtitle: item.subtitle,
    themeEmoji: item.emoji,
    targetLessonsCount: 10,
    lessons: [],
  }))
  return [firstUnit, ...restUnits]
}

